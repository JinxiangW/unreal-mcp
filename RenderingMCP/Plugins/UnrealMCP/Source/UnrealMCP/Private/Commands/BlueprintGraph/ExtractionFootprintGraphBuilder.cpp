UK2Node_Event* FindOrCreateActorEvent(UBlueprint* Blueprint, UEdGraph* Graph, const FName EventName, int32 PosX, int32 PosY)
{
    if (!Blueprint || !Graph)
    {
        return nullptr;
    }

    for (UEdGraphNode* Node : Graph->Nodes)
    {
        if (UK2Node_Event* EventNode = Cast<UK2Node_Event>(Node))
        {
            if (EventNode->EventReference.GetMemberName() == EventName)
            {
                return EventNode;
            }
        }
    }

    UK2Node_Event* EventNode = NewObject<UK2Node_Event>(Graph);
    EventNode->EventReference.SetExternalMember(EventName, AActor::StaticClass());
    EventNode->bOverrideFunction = true;
    EventNode->NodePosX = PosX;
    EventNode->NodePosY = PosY;
    EventNode->CreateNewGuid();
    Graph->AddNode(EventNode, true, false);
    EventNode->PostPlacedNewNode();
    EventNode->AllocateDefaultPins();
    return EventNode;
}

void RemoveGeneratedNodes(UEdGraph* Graph, FBuildStats& Stats)
{
    if (!Graph)
    {
        return;
    }

    TArray<UEdGraphNode*> ToRemove;
    for (UEdGraphNode* Node : Graph->Nodes)
    {
        if (Node && Node->NodeComment == GeneratedComment)
        {
            ToRemove.Add(Node);
        }
    }

    for (UEdGraphNode* Node : ToRemove)
    {
        Node->BreakAllNodeLinks();
        Graph->RemoveNode(Node);
        Stats.NodesRemoved++;
    }
}

