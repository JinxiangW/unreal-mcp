void SetObjectPropertyValue(UObject* Object, const FName PropertyName, UObject* Value, FBuildStats& Stats)
{
    if (!Object)
    {
        return;
    }

    FObjectPropertyBase* Property = FindFProperty<FObjectPropertyBase>(Object->GetClass(), PropertyName);
    if (!Property)
    {
        Stats.Warnings.Add(FString::Printf(TEXT("Object property not found: %s"), *PropertyName.ToString()));
        return;
    }

    Property->SetObjectPropertyValue_InContainer(Object, Value);
}

