bool BuildFootFunction(
    UBlueprint* Blueprint,
    const FName FunctionName,
    const FName FootNameVariable,
    const FName GroundedVariable,
    FBuildStats& Stats)
{
    UEdGraph* Graph = RecreateFunctionGraph(Blueprint, FunctionName);
    if (!Graph)
    {
        Stats.Warnings.Add(FString::Printf(TEXT("Failed to create function graph %s"), *FunctionName.ToString()));
        return false;
    }

    UK2Node_FunctionEntry* Entry = FindFunctionEntry(Graph);
    if (!Entry)
    {
        Stats.Warnings.Add(FString::Printf(TEXT("Function %s has no entry node"), *FunctionName.ToString()));
        return false;
    }

    Entry->NodePosX = 0;
    Entry->NodePosY = 0;

    UK2Node_VariableGet* MeshGet = AddVariableGet(Graph, TEXT("ActiveFootprintMesh"), 0, 180, Stats);
    UK2Node_VariableGet* FootNameGet = AddVariableGet(Graph, FootNameVariable, 0, 340, Stats);
    UK2Node_CallFunction* SocketLoc = AddFunctionCall(Graph, USceneComponent::StaticClass()->FindFunctionByName(TEXT("GetSocketLocation")), 260, 240, Stats);

    UK2Node_CallFunction* StartOffset = AddFunctionCall(Graph, UKismetMathLibrary::StaticClass()->FindFunctionByName(TEXT("MakeVector")), 260, 20, Stats);
    SetPinDefault(FindPin(StartOffset, TEXT("X"), EGPD_Input), TEXT("0.0"));
    SetPinDefault(FindPin(StartOffset, TEXT("Y"), EGPD_Input), TEXT("0.0"));
    SetPinDefault(FindPin(StartOffset, TEXT("Z"), EGPD_Input), TEXT("12.0"));

    UK2Node_CallFunction* EndOffset = AddFunctionCall(Graph, UKismetMathLibrary::StaticClass()->FindFunctionByName(TEXT("MakeVector")), 260, 460, Stats);
    SetPinDefault(FindPin(EndOffset, TEXT("X"), EGPD_Input), TEXT("0.0"));
    SetPinDefault(FindPin(EndOffset, TEXT("Y"), EGPD_Input), TEXT("0.0"));
    SetPinDefault(FindPin(EndOffset, TEXT("Z"), EGPD_Input), TEXT("-35.0"));

    UK2Node_CallFunction* MakeStart = AddFunctionCall(Graph, UKismetMathLibrary::StaticClass()->FindFunctionByName(TEXT("Add_VectorVector")), 520, 80, Stats);
    UK2Node_CallFunction* MakeEnd = AddFunctionCall(Graph, UKismetMathLibrary::StaticClass()->FindFunctionByName(TEXT("Add_VectorVector")), 520, 420, Stats);
    UK2Node_VariableGet* RadiusGet = AddVariableGet(Graph, TEXT("TraceRadius"), 720, 560, Stats);
    UK2Node_CallFunction* Trace = AddFunctionCall(Graph, UKismetSystemLibrary::StaticClass()->FindFunctionByName(TEXT("SphereTraceSingle")), 780, 180, Stats);
    SetPinDefault(FindPin(Trace, TEXT("TraceChannel"), EGPD_Input), TEXT("TraceTypeQuery1"));
    SetPinDefault(FindPin(Trace, TEXT("bTraceComplex"), EGPD_Input), TEXT("false"));
    SetPinDefault(FindPin(Trace, TEXT("DrawDebugType"), EGPD_Input), TEXT("None"));
    SetPinDefault(FindPin(Trace, TEXT("bIgnoreSelf"), EGPD_Input), TEXT("true"));

    UK2Node_IfThenElse* TraceBranch = AddBranch(Graph, 1100, 180, Stats);
    UK2Node_VariableGet* GroundedGet = AddVariableGet(Graph, GroundedVariable, 1100, 390, Stats);
    UK2Node_CallFunction* NotGrounded = AddFunctionCall(Graph, UKismetMathLibrary::StaticClass()->FindFunctionByName(TEXT("Not_PreBool")), 1320, 380, Stats);
    UK2Node_IfThenElse* EdgeBranch = AddBranch(Graph, 1540, 200, Stats);
    UK2Node_CallFunction* BreakHit = AddFunctionCall(Graph, UGameplayStatics::StaticClass()->FindFunctionByName(TEXT("BreakHitResult")), 1320, 20, Stats);
    UK2Node_VariableGet* SystemGet = AddVariableGet(Graph, TEXT("FootprintSystem"), 1540, 20, Stats);
    UK2Node_CallFunction* Spawn = AddFunctionCall(Graph, UNiagaraFunctionLibrary::StaticClass()->FindFunctionByName(TEXT("SpawnSystemAtLocation")), 1780, 120, Stats);
    UK2Node_VariableSet* SetGroundedTrue = AddVariableSet(Graph, GroundedVariable, 2040, 160, Stats);
    UK2Node_VariableSet* SetGroundedFalse = AddVariableSet(Graph, GroundedVariable, 1320, 640, Stats);
    SetPinDefault(FindPin(SetGroundedTrue, GroundedVariable.ToString(), EGPD_Input), TEXT("true"));
    SetPinDefault(FindPin(SetGroundedFalse, GroundedVariable.ToString(), EGPD_Input), TEXT("false"));

    Link(Graph, FindPin(MeshGet, TEXT("ActiveFootprintMesh"), EGPD_Output), FindPin(SocketLoc, TEXT("self"), EGPD_Input), Stats);
    Link(Graph, FindPin(FootNameGet, FootNameVariable.ToString(), EGPD_Output), FindPin(SocketLoc, TEXT("InSocketName"), EGPD_Input), Stats);
    Link(Graph, FindPin(SocketLoc, TEXT("ReturnValue"), EGPD_Output), FindPin(MakeStart, TEXT("A"), EGPD_Input), Stats);
    Link(Graph, FindPin(StartOffset, TEXT("ReturnValue"), EGPD_Output), FindPin(MakeStart, TEXT("B"), EGPD_Input), Stats);
    Link(Graph, FindPin(SocketLoc, TEXT("ReturnValue"), EGPD_Output), FindPin(MakeEnd, TEXT("A"), EGPD_Input), Stats);
    Link(Graph, FindPin(EndOffset, TEXT("ReturnValue"), EGPD_Output), FindPin(MakeEnd, TEXT("B"), EGPD_Input), Stats);
    Link(Graph, FindPin(MakeStart, TEXT("ReturnValue"), EGPD_Output), FindPin(Trace, TEXT("Start"), EGPD_Input), Stats);
    Link(Graph, FindPin(MakeEnd, TEXT("ReturnValue"), EGPD_Output), FindPin(Trace, TEXT("End"), EGPD_Input), Stats);
    Link(Graph, FindPin(RadiusGet, TEXT("TraceRadius"), EGPD_Output), FindPin(Trace, TEXT("Radius"), EGPD_Input), Stats);

    Link(Graph, FindPin(Entry, TEXT("then"), EGPD_Output), FindPin(Trace, TEXT("execute"), EGPD_Input), Stats);
    Link(Graph, FindPin(Trace, TEXT("then"), EGPD_Output), FindPin(TraceBranch, TEXT("execute"), EGPD_Input), Stats);
    Link(Graph, FindPin(Trace, TEXT("ReturnValue"), EGPD_Output), FindPin(TraceBranch, TEXT("Condition"), EGPD_Input), Stats);
    Link(Graph, FindPin(Trace, TEXT("OutHit"), EGPD_Output), FindPin(BreakHit, TEXT("Hit"), EGPD_Input), Stats);
    Link(Graph, FindPin(GroundedGet, GroundedVariable.ToString(), EGPD_Output), FindPin(NotGrounded, TEXT("A"), EGPD_Input), Stats);
    Link(Graph, FindPin(NotGrounded, TEXT("ReturnValue"), EGPD_Output), FindPin(EdgeBranch, TEXT("Condition"), EGPD_Input), Stats);
    Link(Graph, FindPin(TraceBranch, TEXT("then"), EGPD_Output), FindPin(EdgeBranch, TEXT("execute"), EGPD_Input), Stats);
    Link(Graph, FindPin(TraceBranch, TEXT("else"), EGPD_Output), FindPin(SetGroundedFalse, TEXT("execute"), EGPD_Input), Stats);
    Link(Graph, FindPin(EdgeBranch, TEXT("then"), EGPD_Output), FindPin(Spawn, TEXT("execute"), EGPD_Input), Stats);
    Link(Graph, FindPin(SystemGet, TEXT("FootprintSystem"), EGPD_Output), FindPin(Spawn, TEXT("SystemTemplate"), EGPD_Input), Stats);
    Link(Graph, FindPin(BreakHit, TEXT("Location"), EGPD_Output), FindPin(Spawn, TEXT("Location"), EGPD_Input), Stats);
    Link(Graph, FindPin(Spawn, TEXT("then"), EGPD_Output), FindPin(SetGroundedTrue, TEXT("execute"), EGPD_Input), Stats);

    Graph->NotifyGraphChanged();
    return true;
}

